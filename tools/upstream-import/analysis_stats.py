"""Compute every statistic quoted in reports/submission-dataset-analysis.md. Output is JSON-ish text to stdout."""
import json, sys, pathlib, collections, re
out = pathlib.Path(sys.argv[1])
rd = lambda p: [json.loads(l) for l in (out / p).read_text().splitlines() if l.strip()]
C = collections.Counter
issues, prs, comments = rd("raw/issues.jsonl"), rd("raw/pull_requests.jsonl"), rd("raw/issue_comments.jsonl")
norm = rd("normalized/normalized.jsonl")
projs = rd("classified/projects-classified.jsonl")
dd = rd("dedup/projects.jsonl")
summ = json.loads((out / "classified/classification-summary.json").read_text())
man = json.loads((out / "collect-manifest.json").read_text())
errs = (out / "raw/errors.jsonl")
print("== collection ==")
print("manifest counts", man["counts"], "generated", man["generated_at"])
print("raw errors file lines:", len(errs.read_text().splitlines()) if errs.exists() else 0)
print("issue number range", min(i["source_number"] for i in issues), max(i["source_number"] for i in issues), "| numbers present among issues+PRs:", len({i["source_number"] for i in issues} | {p["source_number"] for p in prs}))
nums = {i["source_number"] for i in issues} | {p["source_number"] for p in prs}
mx = max(nums); missing = [n for n in range(1, mx + 1) if n not in nums]
print("gaps in number sequence (deleted/transferred/inaccessible):", len(missing), missing[:20])
print("issues by state", C(i["state"] for i in issues), "| state_reason", C(i["state_reason"] for i in issues))
print("PRs by state", C((p["state"], p["merged"]) for p in prs), "| PRs by author", C(p["author_login"] for p in prs).most_common(5))
print("PRs referencing issues:", sum(1 for r in norm if r["source"]["type"] == "pull_request" and r["source"]["references_issues"]))
print("comments total", len(comments), "| on #1:", sum(1 for c in comments if c["source_number"] == 1), "| elsewhere:", sum(1 for c in comments if c["source_number"] != 1))
print("distinct issue authors", len({i["author_login"] for i in issues}), "| distinct commenters on #1", len({c["author_login"] for c in comments if c["source_number"] == 1}))
print("bot-authored issues", sum(1 for i in issues if i["author_type"] == "Bot"), C(i["author_login"] for i in issues if i["author_type"] == "Bot").most_common(8))
print("\n== submissions over time (issues only, by month) ==")
print(sorted(C(i["created_at"][:7] for i in issues).items()))
print("\n== intents ==")
print(C((r["source"]["type"], r["intent"]) for r in norm))
print("\n== top submitting authors (issues+#1 comments with identity) ==")
byauth = C()
for p in dd:
    for a in p["authors"]: byauth[a] += 1
print("distinct projects per author, top 12:", byauth.most_common(12))
tot = len(dd)
for k in (1, 10, 25, 100):
    print(f"authors with >= {k} projects: {sum(1 for v in byauth.values() if v >= k)}; projects they account for (by authorship overlap, may double-count co-authored): {sum(v for v in byauth.values() if v >= k)}")
print("\n== dedup ==")
print("projects", len(dd), "| source records grouped", sum(p["source_count"] for p in dd), "| dup records", sum(p["source_count"] - 1 for p in dd))
print("projects with >1 sources", sum(1 for p in dd if p["source_count"] > 1), "| single-author dup groups", sum(1 for p in dd if p["source_count"] > 1 and len(p["authors"]) == 1), "| multi-author", sum(1 for p in dd if p["source_count"] > 1 and len(p["authors"]) > 1))
print("merge rules used", C(m["rule"] for p in dd for m in p["merge_reasons"]))
print("ambiguity flags", C(f["code"] for p in dd for f in p["ambiguity_flags"]))
print("top 8 largest groups", [(p["source_count"], p["canonical_key"]) for p in sorted(dd, key=lambda p: -p["source_count"])[:8]])
print("identity types", C(p["identity_type"] for p in dd))
print("claim conflicts present (name/license/repo_url)", C(k for p in dd for k in p["claim_conflicts"]))
print("\n== classification ==")
print(json.dumps({k: summ[k] for k in ["category", "security_concern_projects", "import_ready", "eligible_but_security_flagged", "reason_rule_counts", "github_projects", "github_repos_resolved", "github_repos_unresolved", "renamed", "archived", "stale", "missing_license_of_resolved", "missing_install_info", "incomplete_metadata", "listed_in_official_registry", "ambiguous_projects", "official_registry_entries_loaded", "bulk_submitter_authors", "bulk_submitter_projects"]}, indent=1))
cat = lambda p: p["category"]
print("category x hosting", C((cat(p), p["hosting"]) for p in projs))
print("category x identity", C((cat(p), p["canonical_key"].split("/")[0] if p["canonical_key"].startswith("github.com") else ("endpoint" if p["canonical_key"].startswith("endpoint:") else "package")) for p in projs))
print("quality indicators (all projects)", C(q for p in projs for q in p["quality_indicators"]))
print("quality indicators (eligible)", C(q for p in projs if cat(p) == "eligible" for q in p["quality_indicators"]))
print("needs_review rule breakdown (first rule)", C(p["reasons"][0]["rule"] for p in projs if cat(p) == "needs_review"))
print("\n== upstream state is NOT eligibility (cross-tab) ==")
st = lambda p: "all-closed" if p["upstream_states"] and all(":closed" in s for s in p["upstream_states"]) else ("all-open" if all(":open" in s or "issue_comment" in s for s in p["upstream_states"]) else "mixed")
ddmap = {p["project_id"]: p for p in dd}
print(C((st(ddmap[p["project_id"]]), cat(p)) for p in projs))
print("\n== security flags ==")
print("projects with flags", sum(1 for p in projs if p["security_concern"]), "| by code", C(f.split(":")[0] for p in projs for f in set(p["security_flags"])))
print("flag combos by category", C((cat(p), p["security_concern"]) for p in projs))
print("\n== removal requests / link corrections ==")
for r in rd("classified/removal-requests.jsonl"): print(" removal:", r["record_id"], r["url"], "state", r["state"], "repo_keys", r["repo_keys"], "mcp.so slugs", r.get("mcp_so_slugs"))
for r in rd("classified/link-corrections.jsonl"): print(" link-correction:", r["record_id"], r["url"], r["repo_keys"])
print("\n== language/platform of resolved repos (eligible) ==")
print(C(p["repo"]["language"] for p in projs if cat(p) == "eligible" and p.get("repo") and p["repo"].get("language")).most_common(8))
print("transports claimed (all projects, multi-valued)", C(t for p in projs for t in p["transports"]))
